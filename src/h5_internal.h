/* The instrument and voice enums are not in one-to-one order: the two
 * Hi-hat instruments both map to the Hi-hat voice. Every instrument maps to
 * exactly one voice; the map below is the single source of truth. */
typedef char h5_voice_instrument_order_check[
    ((int)H5_VOICE_KICK == (int)H5_INSTR_KICK &&
     (int)H5_VOICE_SNARE == (int)H5_INSTR_SNARE &&
     (int)H5_VOICE_TOM_1 == (int)H5_INSTR_TOM_1 &&
     (int)H5_VOICE_TOM_2 == (int)H5_INSTR_TOM_2 &&
     (int)H5_VOICE_TOM_3 == (int)H5_INSTR_TOM_3 &&
     (int)H5_VOICE_CYMBAL == (int)H5_INSTR_CYMBAL &&
     (int)H5_VOICE_HIHAT == (int)H5_INSTR_HIHAT_CLOSED &&
     H5_VOICE_COUNT == 7 &&
     H5_INSTR_COUNT == 8) ? 1 : -1];

/* Map a trigger instrument to its parameter voice. The instrument must be
 * in range. */
static inline h5_voice h5_voice_from_instrument(h5_instrument instrument)
{
    static const h5_voice map[H5_INSTR_COUNT] = {
        H5_VOICE_KICK, H5_VOICE_SNARE,
        H5_VOICE_TOM_1, H5_VOICE_TOM_2, H5_VOICE_TOM_3,
        H5_VOICE_CYMBAL, H5_VOICE_HIHAT, H5_VOICE_HIHAT
    };

    return map[(unsigned)instrument < (unsigned)H5_INSTR_COUNT
        ? (unsigned)instrument : 0u];
}

/* True for the open Hi-hat instrument; false for every other target. */
static inline bool h5_instrument_is_open(h5_instrument instrument)
{
    return instrument == H5_INSTR_HIHAT_OPEN;
}

/* Full sine period, one entry per sample of a 1024-step cycle. The oscillator
 * and the filter coefficient setup interpolate between entries, so this is
 * the stored resolution only, not the output resolution. */
#define H5_SINE_TABLE_SIZE 1024

/* First quadrant plus both endpoints: indices 0..256 inclusive. Stored in
 * flash; the other quadrants are mirrored and negated at run time. */
#define H5_SINE_QUAD_SIZE 257

/* Description of one (voice, param) entry. An unsupported entry uses
 * H5_PARAM_UNSUPPORTED as its minimum, which also removes the per-entry
 * support flag and its struct padding. */
#define H5_PARAM_UNSUPPORTED INT32_MIN

struct h5_param_info {
    int32_t min;
    int32_t max;
    int32_t default_value;
};

/* Single source of truth for parameter ranges, defaults and support. */
extern const struct h5_param_info h5_param_table[H5_VOICE_COUNT][H5_PARAM_COUNT];

/* Single source of truth for the FX bus parameter ranges and defaults. */
extern const struct h5_param_info h5_fx_param_table[H5_FX_PARAM_COUNT];

/* First quadrant of the sine, Q15, for i = 0..256. This is the only sine
 * data stored in the image; every other entry is derived from it. */
extern const int16_t h5_sine_quad1[H5_SINE_QUAD_SIZE];

/* The full 1024-entry period, allocated and rebuilt from h5_sine_quad1 on the
 * first h5_create_context(). Shared by every context. Null when the
 * allocation failed; the lookups then fall back to the quadrant. */
extern int16_t *h5_sine;

/* Allocate and rebuild the full sine period. Idempotent and meant to be
 * called once, before any lookup. */
void h5_sine_init(void);

/* Q15 sine of 2*pi*i/H5_SINE_TABLE_SIZE for any index, using the rebuilt
 * table when it is available and the quadrant fallback otherwise. The index
 * must be 0..H5_SINE_TABLE_SIZE-1. */
static inline int16_t h5_sine_at(uint32_t index)
{
    if (h5_sine != 0) {
        return h5_sine[index];
    }
    if (index <= 256u) {
        return h5_sine_quad1[index];
    }
    if (index <= 511u) {
        return h5_sine_quad1[512u - index];
    }
    if (index <= 767u) {
        return (int16_t)-h5_sine_quad1[index - 512u];
    }
    return (int16_t)-h5_sine_quad1[1024u - index];
}

/* Sine interpolation, linear, from the shared table. The 28-bit phase
 * covers one full period; the output is Q31 with the table's amplitude
 * scale (peak 32767 << 16). Exact at integer table indices. */
int32_t h5_sine_interp(uint32_t phase);

/* tan(pi * f / sr) as Q16 from the shared sine table (no libm). Used for
 * the one-pole pre-filter coefficients at parameter change only. */
int32_t h5_tanpi_q16(int32_t f_q16, uint32_t sample_rate);

/* Semitone ratio table: 2^(n/12) as Q16.16 for n = -62..+62. Index n + 62.
 * Generated by tools/gen_semitone_table.py, round-half-up. */
#define H5_SEMITONE_MAX 62
#define H5_SEMITONE_COUNT (2 * H5_SEMITONE_MAX + 1)
extern const int32_t h5_semitone[H5_SEMITONE_COUNT];

/* Fractional lookup: semitones_q16 is a signed Q16.16 semitone count,
 * linearly interpolated between the table entries and clamped to the table
 * range. */
int32_t h5_semitone_ratio_interp(int32_t semitones_q16);

/* x^0.7 as Q14.14 for x in [0, 1], from a 65-entry table (step 1/64) with
 * linear interpolation; h5_pow07_q16() returns Q16.16. Used for the
 * rattle weight of the drum voices, which follows a steep power law. */
#define H5_POW07_SIZE 65
extern const int16_t h5_pow07[H5_POW07_SIZE];
int32_t h5_pow07_q16(int32_t x_q16);

/* Fractional powers in Q16.16, computed with integer square roots when a
 * parameter changes: the square root of a Q16 value, its fourth power
 * (x^0.25) and its eighth power (x^0.125). The drum voices use the soft
 * laws for their balance controls. */
int32_t h5_sqrt_q16(int32_t x_q16);
int32_t h5_pow025_q16(int32_t x_q16);
int32_t h5_pow0125_q16(int32_t x_q16);

/* Soft-clip shaper table: tanh(1.5 * mix) over the argument range [0, 1.5],
 * Q15, sampled in H5_SOFTCLIP_STEPS uniform steps (entry j holds
 * tanh(1.5 * j / H5_SOFTCLIP_STEPS)). The engine mix is Q31, so the lookup
 * index is 24 * |mix| and the entry's argument is 1.5 * |mix|. The result
 * never exceeds tanh(1.5) ~= 0.905, so the shaper's ceiling is one. Generated
 * by tools/gen_softclip_table.py, round-half-up. */
#define H5_SOFTCLIP_SIZE 25
#define H5_SOFTCLIP_STEPS 24
extern const int16_t h5_softclip[H5_SOFTCLIP_SIZE];

/* Shaper: tanh(1.5 * mix) in Q30, with mix in Q31 (1.0 = 1 << 31) and odd
 * symmetry for negative arguments. */
int32_t h5_softclip_q31(int32_t m);

/* Per-voice noise generator state. */
struct h5_noise_s {
    uint32_t x;      /* LCG state */
    uint32_t divider; /* hold length: max(1, sr/48000) */
    uint32_t phase;  /* position in the hold cycle */
    int32_t held;    /* held value, Q31 */
};

/* Initialise a noise generator with the per-voice default seed (distinct
 * and non-zero per voice). */
void h5_noise_init_voice(struct h5_noise_s *n, h5_voice voice,
    uint32_t sample_rate);

/* Advance one output sample and return the held value, Q31 in [-1, 1). */
int32_t h5_noise_next(struct h5_noise_s *n);

/* Envelope phases. */
enum {
    H5_ENV_DONE = 0,
    H5_ENV_ATTACK,
    H5_ENV_RELEASE
};

/* Linear AR envelope state, Q30. 1.0 is exactly 1 << 30, so the peak is
 * representable. */
struct h5_env_s {
    int32_t value;      /* Q30 */
    int32_t delta_a;    /* Q30 per sample, attack */
    int32_t delta_r;    /* Q30 per sample, release */
    int32_t attack_len; /* attack length in samples */
    int32_t release_len; /* release length in samples */
    int32_t count;      /* samples elapsed in the current phase */
    int32_t state;      /* H5_ENV_* */
};

void h5_env_init(struct h5_env_s *e);

/* Set the envelope times. Times are Q16 seconds, clipped non-negative;
 * lengths are truncated to samples with a floor of 1. Running phases keep
 * running with the new deltas. */
void h5_env_set_times(struct h5_env_s *e, int32_t attack_q16,
    int32_t release_q16, uint32_t sample_rate);

/* Restart from the start of the attack. */
void h5_env_trigger(struct h5_env_s *e);

/* Advance one sample and return the Q30 envelope value. */
int32_t h5_env_next(struct h5_env_s *e);

/* Filter modes. */
enum {
    H5_SVF_LP = 0,
    H5_SVF_BP,
    H5_SVF_HP
};

/* Second-order resonant filter, direct-form I. Coefficients are Q30
 * (Q31 samples, 64-bit products); a1 approaches -2. */
struct h5_svf_s {
    int32_t b0;         /* Q30 numerator; the feed-forward terms derive from
                         * it and the mode */
    int32_t a1, a2;     /* Q30 normalised denominators */
    int32_t x1, x2, y1, y2; /* Q31 state */
    int32_t mode;       /* H5_SVF_*; selects the feed-forward identity */
};

void h5_svf_reset(struct h5_svf_s *f);

/* Recompute the coefficients without touching the filter state. Used by
 * engines whose cutoff is swept per sample. */
void h5_svf_tune(struct h5_svf_s *f, int mode, int32_t cutoff_q16,
    int32_t q_q16, uint32_t sample_rate);

/* Advance one sample and return the Q31 output of the configured mode. */
int32_t h5_svf_run(struct h5_svf_s *f, int32_t x);

/* Number of points in a swept-filter coefficient table. The table is built
 * at parameter/sample-rate change, so the audio path replaces the division-
 * heavy h5_svf_tune() with a table lookup and three linear interpolations.
 * Sixteen points over the filter's actual cutoff range keep the coefficient
 * error far below audibility. */
#define H5_SWEEP_POINTS 16

struct h5_sweep_point {
    int32_t b0;
    int32_t a1;
    int32_t a2;
};

struct h5_sweep_s {
    struct h5_sweep_point point[H5_SWEEP_POINTS];
    int32_t lo_q16;   /* cutoff at table index 0, Hz Q16 */
    int32_t step_q32; /* index advance per Hz Q16, scaled by 2^32 */
    int mode;         /* H5_SVF_* */
    uint8_t enabled;  /* false when the cutoff never moves */
};

/* Build the coefficient table for a cutoff that sweeps from lo_q16 to
 * hi_q16. Called only from configure paths, never from the audio loop. */
void h5_sweep_build(struct h5_sweep_s *sw, int mode, int32_t q_q16,
    int32_t lo_q16, int32_t hi_q16, uint32_t sample_rate);

/* Load the coefficients for cutoff_q16 into f. Pure fixed-point arithmetic:
 * no division, and only one multiplication per coefficient. */
void h5_sweep_apply(const struct h5_sweep_s *sw, int32_t cutoff_q16,
    struct h5_svf_s *f);

/* Pitch-increment curve. The oscillator increment follows a smooth function
 * of the cubed tone envelope, so it is precomputed at configure time over
 * env3 = 0..1 and linearly interpolated per sample. H5_PITCH_POINTS + 1
 * entries cover the closed interval; the table lives in the context, not in
 * the static image. */
#define H5_PITCH_POINTS 64
#define H5_PITCH_SHIFT 24

struct h5_pitch_curve_s {
    int32_t inc[H5_PITCH_POINTS + 1];
};

/* The fixed 50 Hz high-pass / 20 kHz low-pass band limit on the held noise.
 * One instance per engine. */
struct h5_pf_s {
    int32_t k50;   /* one-pole coefficient, Q30 */
    int32_t k20;
    int32_t l50;   /* low-pass state, Q31 */
    int32_t l20;
};

/* The fields every engine state starts with. The activity flag sits at a
 * fixed offset, so the dispatch layer can read it without a per-engine
 * accessor. */
struct h5_engine_s {
    uint8_t active;   /* the engine still has output to render */
};

/* The velocity laws of one hit.
 *
 * The strike level is a per-hit quantity, so the engine recomputes these
 * factors at every trigger. `level` is the strike level itself (0..1, Q16),
 * and the three factors are what the engine does with it:
 *
 *   depth = 0.05 + 0.95*level  the pitch envelope sweeps a twentieth of the
 *                                Bend setting at a silent strike and the
 *                                full setting at a hard one
 *   sweep = level^4             the noise cutoff sweeps by 2000*level^4 Hz
 *   click = floor + (1-floor)*level^4
 *                                the transient weight; the floor is 0.3 for
 *                                the Kick and 0.4 for the Snare and Tom
 */
struct h5_velocity_s {
    int32_t level_q16;
    int32_t depth_q16;
    int32_t sweep_q16;
    int32_t click_q16;
};

/* Kick voice runtime state. The engine keeps its own copies of the parameters
 * it needs per sample so the audio path never reads the parameter matrix.
 * Engine outputs are Q30 (1.0 = 1 << 30) with one headroom bit for the
 * shaper stage's overshoot; the mixer converts. */
struct h5_kick_s {
    struct h5_engine_s head;
    struct h5_velocity_s vel;   /* the velocity laws of the current hit */
    struct h5_env_s env_noise;  /* noise AR: ~2 ms attack, Decay release */
    struct h5_env_s env_tone;   /* tone AR: 0.005*Decay attack, Decay release */
    struct h5_env_s env_click;  /* burst AR^10: 1 ms, 0.2*Decay+0.1 release */
    struct h5_noise_s noise;
    struct h5_svf_s noise_filter;
    struct h5_sweep_s noise_sweep;
    struct h5_svf_s out_filter;
    struct h5_pitch_curve_s pitch_curve;
    struct h5_pf_s pf;
    uint32_t phase;          /* 28-bit tone oscillator phase */
    int32_t base_inc;        /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;        /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16; /* noise filter base cutoff, Hz Q16 */
    int32_t tone_gain_q16;   /* 0.85 * NoiseTone^0.125 * (1-Click)^0.25 */
    int32_t noise_gain_q16;  /* 0.4 * (1-NoiseTone)^0.7 * (1-Click)^0.7 */
    int32_t click_gain_q16;  /* 0.66 * Click^0.25 */
};

/* Number of Tom engine instances. H5_VOICE_TOM_1..H5_VOICE_TOM_3 are
 * contiguous in the public enum. */
#define H5_TOM_COUNT 3

/* Number of square oscillators in the metallic bank. */
#define H5_METALLIC_BANK 10

/* Tom voice runtime state. The engine keeps its own copies of the parameters
 * it needs per sample so the audio path never reads the parameter matrix. Each
 * Tom instance has its own envelopes, filters, oscillator and noise state,
 * and its own filter-bend depth (the three tunings differ per instance). */
struct h5_tom_s {
    struct h5_engine_s head;
    struct h5_velocity_s vel;   /* the velocity laws of the current hit */
    struct h5_env_s env;       /* body AR: 0.005*Decay attack, Decay release */
    struct h5_env_s env_click; /* burst AR^10: 1 ms attack, 0.25*Decay */
    struct h5_noise_s noise;
    struct h5_svf_s noise_filter;
    struct h5_sweep_s noise_sweep;
    struct h5_svf_s out_filter;
    struct h5_pitch_curve_s pitch_curve;
    struct h5_pf_s pf;
    uint32_t phase;        /* 28-bit tone oscillator phase */
    int32_t base_inc;      /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;        /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16; /* noise filter base cutoff, Hz Q16 */
    int32_t filter_bend_q16; /* per-instance noise-cutoff bend depth */
    int32_t tone_gain_q16;   /* 0.46 * NoiseTone^0.125 * (1-Click)^0.25 */
    int32_t noise_gain_q16;  /* 0.45 * (1-NoiseTone)^0.7 * (1-Click)^0.7 */
    int32_t click_gain_q16;  /* 0.75 * Click^0.25 */
};

/* Snare voice runtime state. */
struct h5_snare_s {
    struct h5_engine_s head;
    struct h5_velocity_s vel;   /* the velocity laws of the current hit */
    struct h5_env_s env;       /* body AR: 1 ms attack, Decay release */
    struct h5_env_s env_click; /* transient AR^10: 1 ms attack,
                                * 0.2*Decay+0.1 s release */
    struct h5_noise_s noise;
    struct h5_svf_s rattle[4];  /* four fixed band-pass resonators */
    struct h5_svf_s out_filter; /* output low-pass; base cutoff NoisePitch */
    struct h5_sweep_s out_sweep; /* swept coefficients for out_filter */
    struct h5_svf_s hp_filter;  /* output high-pass after the low-pass */
    struct h5_pitch_curve_s pitch_curve;
    struct h5_pf_s pf;
    uint32_t phase;            /* 28-bit tone oscillator phase */
    int32_t base_inc;          /* phase28 increment at TonePitch, no bend */
    int32_t bend_q16;          /* pitch sweep depth in 12ths of an octave */
    int32_t noise_pitch_q16;   /* output low-pass base cutoff */
    int32_t tone_gain_q16;     /* NoiseTone^0.125 * (1-Click)^0.25 */
    int32_t noise_gain_q16;    /* 0.3 * (1-NoiseTone)^0.7 * (1-Click)^0.7 */
    int32_t click_gain_q16;    /* 63/80 * Click^0.25 */
};

/* Metallic voice runtime state, shared by the Cymbal and the Hi-hat. The
 * engine keeps its own copies of the parameters it needs per sample so the
 * audio path never reads the parameter matrix. */
struct h5_metallic_s {
    struct h5_engine_s head;
    struct h5_velocity_s vel;   /* only the strike level is used */
    struct h5_env_s env_metal;  /* AR: the metal envelope */
    struct h5_env_s env_noise;  /* AR: the noise envelope */
    struct h5_noise_s noise;
    struct h5_svf_s noise_filter;  /* the first low-pass of the noise path */
    struct h5_svf_s noise_filter2; /* the second low-pass of the noise path */
    struct h5_sweep_s noise_sweep; /* its coefficients over the sweep range */
    uint32_t phase[H5_METALLIC_BANK];  /* 28-bit phases */
    int32_t inc[H5_METALLIC_BANK];     /* phase increments, bend included */
    int32_t base_inc[H5_METALLIC_BANK]; /* phase increments without the bend */
    int32_t metal_gain_q16;   /* the Bell/Cymbal balance */
    int32_t noise_gain_q16;   /* the Noise/Tone balance and the noise weight */
    int32_t filter_freq_q16;  /* the noise filter's base cutoff, Hz Q16 */
    int32_t sweep_q16;        /* the filter contour depth, signed Q16 */
    int32_t bend_q16;         /* the pitch sweep of the bank, semitones Q16 */
    int32_t drive_q16;        /* the saturation blend */
    int32_t decay_q16;        /* the release time, seconds Q16 */
    int32_t hp_k_q30;         /* the noise high-pass coefficient */
    int32_t hp_state;         /* the noise high-pass state, Q31 */
    int32_t hp_state2;        /* the second noise high-pass state, Q31 */
    int32_t fc_const_q16;     /* the noise filter's cutoff when the sweep is 0 */
    int32_t open_q16;         /* the Open amount, seconds Q16 */
    uint8_t open;               /* Hi-hat: the hit was triggered open */
    uint8_t has_open;           /* Hi-hat only; 0 for the Cymbal */
};

/* One reverb comb line. The delay line lives inside the single FX block. */
#define H5_FX_COMBS 8
#define H5_FX_ALLPASSES 4

struct h5_comb_s {
    int16_t *line;   /* into fx.block */
    uint32_t alloc;  /* allocated length in samples (fixed at 48 kHz) */
    uint32_t pos;    /* write position, wraps at alloc */
    uint32_t len;    /* active delay length, set by configure */
    int32_t lp;      /* damping one-pole state, Q31 */
};

struct h5_allpass_s {
    int16_t *line;
    uint32_t alloc;
    uint32_t pos;
    uint32_t len;    /* fixed at configure time, wraps at len */
};

/* Noise-gate states. */
enum {
    H5_FX_GATE_CLOSED = 0,
    H5_FX_GATE_OPENING,
    H5_FX_GATE_OPEN,
    H5_FX_GATE_HOLDING,
    H5_FX_GATE_RELEASING
};

/* The shared FX bus: one stereo reverb and one stereo-linked noise gate. */
struct h5_fx_s {
    int16_t *block;         /* one allocation, carved into the lines */
    size_t block_size;      /* bytes, for teardown and diagnostics */
    struct h5_comb_s comb[2][H5_FX_COMBS];
    struct h5_allpass_s allpass[2][H5_FX_ALLPASSES];

    int32_t damp_q16;       /* damping one-pole coefficient */
    int32_t width_q31;      /* stereo width, Q31 */
    int32_t wet_q31;        /* return trim after the gate, Q31 */
    int32_t room_q16;       /* stored room size for configure() */

    /* Gate. */
    int32_t key_env;        /* pre-reverb |bus| peak follower, Q31 */
    int32_t out_env;        /* post-gate |wet| follower, Q31 */
    int32_t gate_gain;      /* Q31, floor..FULL */
    int32_t floor_q31;      /* (1 - RANGE) in Q31; FULL when bypassed */
    int32_t thr_open_q31;   /* threshold in Q31 */
    int32_t thr_close_q31;  /* thr_open >> 1 */
    uint32_t hold_count;    /* samples left in HOLDING */
    uint32_t hold_samples;  /* HOLD at the current rate */
    int32_t atk_delta;      /* gain step per sample while opening */
    int32_t rel_delta;      /* gain step per sample while releasing */
    uint8_t state;          /* H5_FX_GATE_* */
};

/* The concrete context behind the opaque h5_context handle. */
struct h5_context_s {
    uint32_t sample_rate;

    /* Per-voice public parameters, stored as Q16.16 physical values. The
     * mixer controls Volume and Pan live here; the precomputed stereo
     * gains below are derived from them. */
    int32_t voice_params[H5_VOICE_COUNT][H5_PARAM_COUNT];

    /* Mixer stereo gains, Q16: volume * (1 - pan) and volume * pan. Updated
     * when Volume or Pan changes, never on the audio path. */
    int32_t mix_left[H5_VOICE_COUNT];
    int32_t mix_right[H5_VOICE_COUNT];

    /* FX bus. The send gains are the mixer gains folded with H5_PARAM_FX_SEND
     * and are cached like the dry gains. fx_any_send is 1 when at least one
     * send gain is non-zero; the bus is bypassed otherwise. */
    int32_t fx_send[H5_VOICE_COUNT];
    int32_t fx_gain_left[H5_VOICE_COUNT];
    int32_t fx_gain_right[H5_VOICE_COUNT];
    int32_t fx_params[H5_FX_PARAM_COUNT];
    uint8_t fx_any_send;
    struct h5_fx_s fx;

    /* Bit i is set while voice i is sounding. h5_process() only visits the
     * set bits, so silent voices cost nothing beyond the trigger bookkeeping.
     * Bits are cleared as their engines finish during rendering. */
    uint32_t active_mask;

    /* Per-instrument peak level for the most recent h5_process() block, in
     * Q16.16 (0 .. H5_Q16_ONE). This is the mono signal level after the
     * instrument's own volume but before the stereo pan/sum, so a host can
     * drive per-instrument activity indicators independently of the final
     * mix. Reset at the start of every h5_process() call and updated only
     * while the voice is active. */
    int32_t voice_level[H5_INSTR_COUNT];

    /* Voice runtime state, initialized by h5_voice_setup_all(). The Toms are
     * three independent instances of the same engine. The Cymbal and the
     * Hi-hat share the metallic engine with per-voice configuration. */
    struct h5_kick_s kick;
    struct h5_tom_s tom[H5_TOM_COUNT];
    struct h5_snare_s snare;
    struct h5_metallic_s cymbal;
    struct h5_metallic_s hihat;
};

/* The engine operations. One set per engine type; the three Toms share the
 * Tom set. The engine pointer addresses the concrete engine state that
 * belongs to the set, so a set and a state must always be paired.
 *
 * setup resets the engine state and then applies the parameters; configure
 * applies the parameters alone, so that a parameter change does not cut a
 * sounding voice. */
struct h5_engine_ops {
    void (*setup)(void *engine, h5_voice voice,
        const int32_t params[H5_PARAM_COUNT], uint32_t sample_rate);
    void (*configure)(void *engine,
        const int32_t params[H5_PARAM_COUNT], uint32_t sample_rate);
    /* variant: 0 for a normal hit, 1 for the open Hi-hat character.
     * Engines without an open character ignore it. */
    void (*trigger)(void *engine, int32_t level_q16, uint32_t sample_rate,
        uint32_t variant);
    int32_t (*process)(void *engine);
};

extern const struct h5_engine_ops h5_kick_ops;
extern const struct h5_engine_ops h5_snare_ops;
extern const struct h5_engine_ops h5_tom_ops;
extern const struct h5_engine_ops h5_cymbal_ops;
extern const struct h5_engine_ops h5_hihat_ops;

/* One voice's binding to an engine instance: the operation set it runs and
 * where its engine state sits inside the context. */
struct h5_voice_slot {
    const struct h5_engine_ops *ops;
    size_t offset;   /* byte offset of the engine state in the context */
};

extern const struct h5_voice_slot h5_voice_slots[H5_VOICE_COUNT];

