int32_t h5_bell_interp(uint32_t phase)
{
    uint32_t idx, frac;
    int32_t a, b;
    int64_t v;

    phase &= 0x0FFFFFFFu;
    idx = phase >> 16;
    frac = phase & 0xFFFFu;
    a = h5_bell[idx];
    b = h5_bell[(idx + 1u) & (H5_BELL_SIZE - 1u)];
    /* Q15 table entries: a * 65536 makes the result Q31, and the 16-bit
     * fraction weighs one full Q16 step between entries. */
    v = (int64_t)a * 65536 + h5_mulwide(b - a, (int32_t)frac);
    return h5_sat_i32(v);
}
