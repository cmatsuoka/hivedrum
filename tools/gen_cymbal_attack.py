#!/usr/bin/env python3
"""Build the short strike table used by the Cymbal engine.

The table is a consensus transient measured from several recordings of the
instrument's cymbal, aligned at the strike and averaged.  The average keeps
the part every take shares and suppresses the parts that differ, so the
table carries the common strike without the room and take-to-take noise.

Usage: python3 tools/gen_cymbal_attack.py SDS5_cymbal*.wav > src/h5_cymbal_table.c
"""
import wave
import sys
import numpy as np

RATE = 48000
LENGTH = 2880
REFERENCE = 5


def read(path):
    w = wave.open(path, 'rb')
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3)
    v = (b[:, 0].astype(np.int32)
         | (b[:, 1].astype(np.int32) << 8)
         | (b[:, 2].astype(np.int32) << 16))
    v = np.where(v >= 2 ** 23, v - 2 ** 24, v)
    return v.astype(np.float64) / 2 ** 23


def onset(x):
    th = 0.02 * np.max(np.abs(x))
    return int(np.argmax(np.abs(x) > th))


def main(paths):
    xs = []
    for p in paths:
        x = read(p)
        xs.append(x[onset(x):])
    if len(xs) <= REFERENCE:
        raise SystemExit('not enough recordings')
    ref = xs[REFERENCE][:int(0.15 * RATE)]
    segs = []
    for k in range(len(xs)):
        if k in (0, 1):
            continue
        best = (-9.0, 0)
        for lag in range(-80, 81):
            y = xs[k][lag:lag + len(ref)]
            if len(y) < len(ref):
                continue
            a = ref - ref.mean()
            b = y - y.mean()
            c = np.sum(a * b) / np.sqrt(
                np.sum(a * a) * np.sum(b * b) + 1e-30)
            if c > best[0]:
                best = (c, lag)
        y = xs[k][max(0, best[1]):max(0, best[1]) + int(0.15 * RATE)]
        rms = np.sqrt(np.mean(y[:int(0.03 * RATE)] ** 2))
        segs.append(y / rms)
    length = min(len(s) for s in segs)
    avg = np.mean(np.array([s[:length] for s in segs]), axis=0)
    peak = np.max(np.abs(avg))
    start = int(np.argmax(np.abs(avg) > 0.05 * peak))
    seg = avg[start:start + LENGTH].copy()
    fade = int(0.002 * RATE)
    seg[-fade:] *= np.linspace(1.0, 0.0, fade)
    seg /= np.max(np.abs(seg)) + 1e-12
    values = np.clip(seg * 32767.0, -32768, 32767).astype(int)

    print('/* Generated by tools/gen_cymbal_attack.py. */')
    print('#include "h5_internal.h"')
    print('#if defined(LIBHIVE_ENGINE_CYMBAL)')
    print('')
    print('/* The cymbal strike table: a short consensus transient measured')
    print(' * from the instrument, one entry per sample at 48 kHz. */')
    print('const int16_t h5_cymbal_attack[H5_CYMBAL_ATTACK_LEN] = {')
    for i in range(0, len(values), 12):
        row = values[i:i + 12]
        print('    ' + ', '.join('%6d' % v for v in row) + ',')
    print('};')
    print('')
    print('#endif /* LIBHIVE_ENGINE_CYMBAL */')


if __name__ == '__main__':
    main(sys.argv[1:])
