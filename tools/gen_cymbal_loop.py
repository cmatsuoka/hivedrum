#!/usr/bin/env python3
"""Build the short loop table used by the Cymbal engine.

The table is derived from a recorded cymbal hit: a sustain window after the
attack has faded is flattened, its slow filter colour is optionally
equalised, and a short segment is kept as a loop.  The default window is
taken from the point where the loop tone is clearest and still well above
the recording's noise floor.  A light whitening evens out the fixed colour of the
recording, so the sampled body keeps a richer, less resonant spectrum.  A
pair of peaking cuts trims the loop's body and presence so it blends with
the noise wash; a sampled-data equaliser costs nothing at run time.  It is
not the original stored waveform; it is a cleaned, plausible loop used as
the engine's sampled metallic source.

Usage: python3 tools/gen_cymbal_loop.py input.wav > src/h5_cymbal_loop.c
"""
import wave
import sys
import numpy as np

RATE = 48000
LENGTH = 2400
START = 0.20
SEGMENT = 0.30
WHITEN = 0.4

# The loop runs at Tone Pitch 0.55 by default, so these loop-domain
# frequencies land near 800 Hz (body) and 2 kHz (presence) at playback.
BODY_HZ = 1450.0
BODY_DB = -4.0
BODY_Q = 1.2
PRESENCE_HZ = 3600.0
PRESENCE_DB = -8.0
PRESENCE_Q = 1.0


def peaking_response(freqs, f0, gain_db, q):
    """Magnitude of an RBJ peaking stage at the given frequencies."""
    a = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * np.pi * f0 / RATE
    alpha = np.sin(w0) / (2.0 * q)
    cosw0 = np.cos(w0)
    b = np.array([1.0 + alpha * a, -2.0 * cosw0, 1.0 - alpha * a])
    d = np.array([1.0 + alpha / a, -2.0 * cosw0, 1.0 - alpha / a])
    z1 = np.exp(-1j * 2.0 * np.pi * freqs / RATE)
    z2 = z1 * z1
    h = (b[0] + b[1] * z1 + b[2] * z2) / (d[0] + d[1] * z1 + d[2] * z2)
    return np.abs(h)


def read(path):
    w = wave.open(path, 'rb')
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3)
    v = (b[:, 0].astype(np.int32)
         | (b[:, 1].astype(np.int32) << 8)
         | (b[:, 2].astype(np.int32) << 16))
    v = np.where(v >= 2 ** 23, v - 2 ** 24, v)
    return v.astype(np.float64) / 2 ** 23


def onset(x):
    th = 0.02 * np.max(np.abs(x))
    return int(np.argmax(np.abs(x) > th))


def smooth(y, n):
    k = np.ones(n) / n
    return np.convolve(y, k, mode='same')


def main(path):
    x = read(path)
    x = x[onset(x):]
    seg = x[int(START * RATE):int((START + SEGMENT) * RATE)].copy()
    seg -= seg.mean()

    # Flatten the VCA envelope with a 20 ms RMS follower. The segment is
    # reflect-padded so the follower has no zero-padded edge dip.
    win = int(0.02 * RATE)
    pad = win // 2
    power = np.pad(seg * seg, (pad, pad), mode='reflect')
    env = np.sqrt(np.convolve(power, np.ones(win) / win, mode='same'))
    env = env[pad:pad + len(seg)]
    seg = seg / (env + 1e-6)

    # Optionally invert the fixed filter colour.  A smoothed magnitude
    # spectrum is used as the equaliser; the exponent keeps the result
    # natural instead of fully white.
    n = len(seg)
    nfft = 1 << (n - 1).bit_length()
    spec = np.fft.rfft(seg, nfft)
    mag = np.abs(spec)
    eq = (smooth(mag, 129) / (mag.mean() + 1e-12)) ** (-WHITEN)
    eq = np.clip(eq, 0.15, 8.0)
    seg = np.fft.irfft(spec * eq, nfft)[:n]

    # Remove the remaining very low end and trim the body/presence
    # balance. The peaking magnitudes are zero-phase, so the loop keeps the
    # attack-free segment's shape and needs no settling time.
    f = np.fft.rfftfreq(nfft, 1.0 / RATE)
    spec = np.fft.rfft(seg, nfft)
    spec[f < 100.0] = 0.0
    spec *= peaking_response(f, BODY_HZ, BODY_DB, BODY_Q)
    spec *= peaking_response(f, PRESENCE_HZ, PRESENCE_DB, PRESENCE_Q)
    seg = np.fft.irfft(spec, nfft)[:n]

    seg = seg[:LENGTH].copy()
    seg -= seg.mean()
    seg /= np.max(np.abs(seg)) + 1e-12
    values = np.clip(seg * 0.9 * 32767.0, -32768, 32767).astype(int)

    print('/* Generated by tools/gen_cymbal_loop.py. */')
    print('#include "h5_internal.h"')
    print('#if defined(LIBHIVE_ENGINE_CYMBAL)')
    print('')
    print('/* The cymbal loop table: a cleaned 50 ms sustain segment.')
    print(' * It is played forward/backward under the wash envelope. */')
    print('const int16_t h5_cymbal_loop[H5_CYMBAL_LOOP_LEN] = {')
    for i in range(0, len(values), 12):
        row = values[i:i + 12]
        print('    ' + ', '.join('%6d' % v for v in row) + ',')
    print('};')
    print('')
    print('#endif /* LIBHIVE_ENGINE_CYMBAL */')


if __name__ == '__main__':
    main(sys.argv[1])
